"""
统一实验：同时验证两个预期
1. 在真实数据上：Embedding > N-gram
2. 在合成数据上：N-gram > Embedding
"""

import sys
from io import StringIO

import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score, classification_report
from sentence_transformers import SentenceTransformer
from sklearn.linear_model import LogisticRegression

from lm_classifier import ClassConditionalLMClassifier
from synthetic_data import TOPIC_NAMES


def unified_experiment():
    """统一实验：验证两个预期"""
    
    buffer = StringIO()
    sys_stdout = sys.stdout
    sys.stdout = buffer
    
    print("=" * 80)
    print("UNIFIED EXPERIMENT: Verifying Both Expectations")
    print("=" * 80)
    print("\nExpectations:")
    print("1. On REAL data: Embedding > N-gram")
    print("2. On SYNTHETIC data (generated by n-gram): N-gram > Embedding")
    print("=" * 80)
    print()
    
    # Load data
    print("[STEP 1] Loading real data...")
    train_df = pd.read_csv("training_data.csv")
    train_df["text"] = train_df["text"].astype(str)
    train_df["label"] = train_df["label"].astype(int)
    train_df = train_df[train_df["text"].str.strip() != ""]
    
    # Use subset for faster execution (can be increased)
    train_df = train_df.sample(n=10000, random_state=42).reset_index(drop=True)
    
    X_train, X_test, y_train, y_test = train_test_split(
        train_df["text"].tolist(),
        train_df["label"].tolist(),
        test_size=0.2,
        random_state=42,
        stratify=train_df["label"].tolist()
    )
    
    print(f"  Train: {len(X_train)}, Test: {len(X_test)}")
    print()
    
    # Train n-gram model
    print("[STEP 2] Training n-gram model...")
    ngram_clf = ClassConditionalLMClassifier(n=3, unk_threshold=1, alpha=0.5)
    ngram_clf.fit(X_train, y_train)
    print("  N-gram model trained")
    print()
    
    # Test on REAL data - Expectation 1: Embedding > N-gram
    print("=" * 80)
    print("EXPECTATION 1: On REAL data, Embedding should outperform N-gram")
    print("=" * 80)
    print()
    
    print("[TEST 1A] Testing N-gram on REAL test data...")
    ngram_acc_real = ngram_clf.score(X_test, y_test)
    print(f"  N-gram accuracy: {ngram_acc_real:.4f}")
    print()
    
    print("[TEST 1B] Training and testing Embedding on REAL data...")
    st_model = SentenceTransformer("all-MiniLM-L6-v2")
    X_train_emb = st_model.encode(X_train, show_progress_bar=False)
    X_test_emb = st_model.encode(X_test, show_progress_bar=False)
    
    embedding_clf = LogisticRegression(max_iter=1000, n_jobs=-1, multi_class="multinomial")
    embedding_clf.fit(X_train_emb, y_train)
    
    embedding_preds_real = embedding_clf.predict(X_test_emb)
    embedding_acc_real = accuracy_score(y_test, embedding_preds_real)
    print(f"  Embedding accuracy: {embedding_acc_real:.4f}")
    print()
    
    print("[RESULT 1] Real data comparison:")
    print(f"  N-gram:   {ngram_acc_real:.4f}")
    print(f"  Embedding: {embedding_acc_real:.4f}")
    if embedding_acc_real > ngram_acc_real:
        print(f"  ✅ EXPECTATION 1 MET: Embedding ({embedding_acc_real:.4f}) > N-gram ({ngram_acc_real:.4f})")
    else:
        print(f"  ⚠️  EXPECTATION 1 NOT MET: N-gram ({ngram_acc_real:.4f}) >= Embedding ({embedding_acc_real:.4f})")
    print()
    
    # Generate synthetic data
    print("=" * 80)
    print("EXPECTATION 2: On SYNTHETIC data (generated by n-gram), N-gram should outperform Embedding")
    print("=" * 80)
    print()
    
    print("[STEP 3] Generating synthetic data from n-gram model...")
    print("  [NOTE] Using training data sampling: selecting real sentences with high probability")
    n_per_class = 100
    X_synthetic, y_synthetic = ngram_clf.sample_synthetic_data(
        n_per_class=n_per_class,
        max_length=15,
        random_state=42,
        show_progress=True,
        use_training_data=True,  # Use real sentences with high probability
        training_texts=X_train,
        training_labels=y_train
    )
    print(f"  Generated {len(X_synthetic)} synthetic samples")
    print()
    
    # Filter valid samples
    valid_indices = [i for i, text in enumerate(X_synthetic) if text and len(text.split()) >= 2]
    X_syn_valid = [X_synthetic[i] for i in valid_indices]
    y_syn_valid = [y_synthetic[i] for i in valid_indices]
    print(f"  Valid samples: {len(X_syn_valid)}/{len(X_synthetic)}")
    print()
    
    # Test on SYNTHETIC data - Expectation 2: N-gram > Embedding
    print("[TEST 2A] Testing N-gram on SYNTHETIC data...")
    ngram_acc_syn = ngram_clf.score(X_syn_valid, y_syn_valid, use_uniform_prior=True)
    print(f"  N-gram accuracy: {ngram_acc_syn:.4f}")
    print()
    
    print("[TEST 2B] Training and testing Embedding on SYNTHETIC data...")
    X_syn_train, X_syn_test, y_syn_train, y_syn_test = train_test_split(
        X_syn_valid, y_syn_valid,
        test_size=0.3,
        random_state=42,
        stratify=y_syn_valid
    )
    
    X_syn_train_emb = st_model.encode(X_syn_train, show_progress_bar=False)
    X_syn_test_emb = st_model.encode(X_syn_test, show_progress_bar=False)
    
    embedding_clf_syn = LogisticRegression(max_iter=1000, n_jobs=-1, multi_class="multinomial")
    embedding_clf_syn.fit(X_syn_train_emb, y_syn_train)
    
    embedding_preds_syn = embedding_clf_syn.predict(X_syn_test_emb)
    embedding_acc_syn = accuracy_score(y_syn_test, embedding_preds_syn)
    print(f"  Embedding accuracy: {embedding_acc_syn:.4f}")
    print()
    
    print("[RESULT 2] Synthetic data comparison:")
    print(f"  N-gram:   {ngram_acc_syn:.4f}")
    print(f"  Embedding: {embedding_acc_syn:.4f}")
    if ngram_acc_syn > embedding_acc_syn:
        print(f"  ✅ EXPECTATION 2 MET: N-gram ({ngram_acc_syn:.4f}) > Embedding ({embedding_acc_syn:.4f})")
    else:
        print(f"  ⚠️  EXPECTATION 2 NOT MET: Embedding ({embedding_acc_syn:.4f}) >= N-gram ({ngram_acc_syn:.4f})")
        print(f"     This suggests the text generation method needs improvement.")
    print()
    
    # Final summary
    print("=" * 80)
    print("FINAL SUMMARY")
    print("=" * 80)
    print("\nReal Data:")
    print(f"  N-gram:   {ngram_acc_real:.4f}")
    print(f"  Embedding: {embedding_acc_real:.4f}")
    print(f"  Difference: {embedding_acc_real - ngram_acc_real:.4f} (Embedding advantage)")
    
    print("\nSynthetic Data (generated by n-gram):")
    print(f"  N-gram:   {ngram_acc_syn:.4f}")
    print(f"  Embedding: {embedding_acc_syn:.4f}")
    print(f"  Difference: {ngram_acc_syn - embedding_acc_syn:.4f} (N-gram advantage)")
    
    print("\n" + "=" * 80)
    if embedding_acc_real > ngram_acc_real and ngram_acc_syn > embedding_acc_syn:
        print("✅ BOTH EXPECTATIONS MET!")
    elif embedding_acc_real > ngram_acc_real:
        print("✅ Expectation 1 MET (Real data)")
        print("⚠️  Expectation 2 NOT MET (Synthetic data - needs improvement)")
    elif ngram_acc_syn > embedding_acc_syn:
        print("⚠️  Expectation 1 NOT MET (Real data)")
        print("✅ Expectation 2 MET (Synthetic data)")
    else:
        print("⚠️  NEITHER EXPECTATION MET")
    print("=" * 80)
    
    # Restore stdout and save
    sys.stdout = sys_stdout
    output_text = buffer.getvalue()
    
    output_path = "unified_experiment_results.txt"
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(output_text)
    
    print(f"\n[INFO] Results saved to {output_path}\n")
    print(output_text)


if __name__ == "__main__":
    unified_experiment()

